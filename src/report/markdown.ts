import type { Finding, Sensitivity, Severity } from '../types';
import { compareFindings, countBySeverity } from '../utils/findings';

/**
 * Markdown report renderer.
 *
 * The report is the only artifact a run produces, so it carries:
 *   - what was scanned and at which sensitivity,
 *   - one row per finding with file:line:column,
 *   - the financial risk and the suggested fix,
 *   - an explicit reminder that nothing was executed and no key was read.
 *
 * The `REPORT_MARKER` comment lets the action find and update its own PR comment instead of
 * posting a duplicate on every push.
 */

export const REPORT_MARKER = '<!-- payfuzz-report -->';

export interface MarkdownReportOptions {
  findings: readonly Finding[];
  /** Repository-relative paths of the payment files that were scanned. */
  scannedFiles?: readonly string[];
  sensitivity?: Sensitivity;
  generatedAt?: Date;
  version?: string;
}

const SEVERITY_BADGE: Record<Severity, string> = {
  high: '🔴 high',
  medium: '🟠 medium',
  low: '🟡 low',
};

export function renderMarkdownReport(options: MarkdownReportOptions): string {
  const generatedAt = options.generatedAt ?? new Date();
  const version = options.version ?? '0.1.0';
  const scannedFiles = options.scannedFiles ?? [];
  const sensitivity = options.sensitivity;
  const findings = [...options.findings].sort(compareFindings);
  const counts = countBySeverity(findings);

  const lines: string[] = [];
  lines.push(REPORT_MARKER, '');
  lines.push('# PayFuzz report', '');
  lines.push(
    '> Simulated in memory on your CI runner. PayFuzz parsed your source — it did not execute it, did not read a key, and did not move money. Security model: [SECURITY.md](SECURITY.md).',
    '',
  );

  if (findings.length === 0) {
    lines.push('## No payment-logic issues found', '');
    lines.push(
      `PayFuzz scanned **${scannedFiles.length}** payment file${plural(scannedFiles.length)} and matched none of the enabled scenarios.`,
      '',
    );
    lines.push(
      '> A clean report is not proof of correctness. It means the enabled scenarios did not match the scanned files — not that the code is safe.',
      '',
    );
  } else {
    const affectedFiles = new Set(findings.map((finding) => finding.file)).size;
    lines.push(
      `**${counts.high} high · ${counts.medium} medium · ${counts.low} low** — ${findings.length} finding${plural(findings.length)} in ${affectedFiles} file${plural(affectedFiles)}.`,
      '',
    );
    lines.push(
      `Scanned **${scannedFiles.length}** payment file${plural(scannedFiles.length)}${sensitivity === undefined ? '' : ` at sensitivity \`${sensitivity}\``} with PayFuzz \`${version}\`.`,
      '',
    );

    lines.push('## Summary', '');
    lines.push('| # | Severity | Scenario | Location | Finding |');
    lines.push('| --- | --- | --- | --- | --- |');
    findings.forEach((finding, index) => {
      lines.push(
        `| ${index + 1} | ${SEVERITY_BADGE[finding.severity]} | \`${finding.scenario}\` | \`${finding.file}:${finding.line}:${finding.column}\` | ${escapeTableCell(finding.title)} |`,
      );
    });
    lines.push('');

    lines.push('## Findings', '');
    findings.forEach((finding, index) => {
      lines.push(`### ${index + 1}. ${SEVERITY_BADGE[finding.severity]} — ${finding.title}`, '');
      lines.push(
        `**Scenario:** \`${finding.scenario}\` · **Rule:** \`${finding.rule}\` · **Location:** \`${finding.file}:${finding.line}:${finding.column}\``,
        '',
      );
      lines.push(fencedCode(finding.snippet, languageFor(finding.file)), '');
      if (finding.evidence !== undefined) {
        lines.push(`**Simulated:** ${finding.evidence}`, '');
      }
      lines.push(`**Financial risk:** ${finding.risk}`, '');
      lines.push(`**Suggested fix:** ${finding.fix}`, '');
    });
  }

  if (scannedFiles.length > 0) {
    lines.push('<details>', `<summary>Files scanned (${scannedFiles.length})</summary>`, '');
    for (const file of scannedFiles) lines.push(`- \`${file}\``);
    lines.push('', '</details>', '');
  }

  lines.push('---', '');
  lines.push(
    `<sub>Generated by PayFuzz \`${version}\` at ${generatedAt.toISOString()} · ${scannedFiles.length} payment file${plural(scannedFiles.length)} scanned · no code executed, no network calls, no keys read.<br />Found a security problem in PayFuzz itself? See [SECURITY.md](SECURITY.md).</sub>`,
  );

  return `${lines.join('\n').trimEnd()}\n`;
}

function plural(count: number): string {
  return count === 1 ? '' : 's';
}

function languageFor(file: string): string {
  const extension = file.slice(file.lastIndexOf('.') + 1).toLowerCase();
  if (extension === 'ts' || extension === 'tsx') return 'ts';
  if (extension === 'js' || extension === 'jsx' || extension === 'mjs' || extension === 'cjs') {
    return 'js';
  }
  if (extension === 'py') return 'python';
  return 'text';
}

function escapeTableCell(value: string): string {
  return value.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

/** Pick a fence longer than any backtick run inside the snippet, so the snippet stays intact. */
function fencedCode(code: string, language: string): string {
  const runs = code.match(/`+/g) ?? [];
  const longestRun = runs.reduce((longest, run) => Math.max(longest, run.length), 0);
  const fence = '`'.repeat(Math.max(3, longestRun + 1));
  return `${fence}${language}\n${code}\n${fence}`;
}
